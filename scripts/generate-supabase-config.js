const fs = require("fs");
const path = require("path");

const supabaseUrl = process.env.SUPABASE_URL;
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY;

if (!supabaseUrl) {
  throw new Error("SUPABASE_URL environment variable is missing.");
}

if (!supabaseAnonKey) {
  throw new Error("SUPABASE_ANON_KEY environment variable is missing.");
}

const output = `/* AUTO-GENERATED BY NETLIFY BUILD - DO NOT EDIT */

window.SUPABASE_URL = ${JSON.stringify(supabaseUrl)};
window.SUPABASE_ANON_KEY = ${JSON.stringify(supabaseAnonKey)};
`;

const outputPath = path.join(
  __dirname,
  "..",
  "js",
  "supabase-config.js"
);

fs.writeFileSync(outputPath, output, "utf8");

console.log("Supabase configuration generated successfully.");
